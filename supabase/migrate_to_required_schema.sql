-- One-time migration: reshapes a database built by the earlier schema.sql into
-- the schema required by the Final Exam manual, keeping every product, order and
-- account. A fresh project doesn't need this: run schema.sql instead.
-- Runs as one transaction in the SQL editor, so it applies fully or not at all.

-- roles: id int8 (identity), role varchar, created_at, encoded_by -> auth.users
alter table public.profiles drop constraint if exists profiles_role_id_fkey;
alter table public.roles alter column id type bigint;
alter table public.profiles alter column role_id type bigint;
alter table public.roles alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.roles', 'id'), (select max(id) from public.roles));
alter table public.roles rename column name to role;
alter table public.roles alter column role type varchar(20);
alter table public.roles add column created_at timestamptz not null default now();
alter table public.roles add column encoded_by uuid references auth.users (id) on delete set null;
alter table public.profiles
  add constraint profiles_role_id_fkey foreign key (role_id) references public.roles (id);

-- profiles: firstname + lastname instead of full_name; no avatar_url
alter table public.profiles add column firstname text;
alter table public.profiles add column lastname text;
update public.profiles set
  firstname = nullif(split_part(full_name, ' ', 1), ''),
  lastname  = nullif(substr(full_name, length(split_part(full_name, ' ', 1)) + 2), '');
alter table public.profiles drop column full_name;
alter table public.profiles drop column avatar_url;
grant update (firstname, lastname) on public.profiles to authenticated;

-- orders: user_id -> auth.users
alter table public.orders drop constraint orders_user_id_fkey;
alter table public.orders
  add constraint orders_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade;

-- order_items: created_at; quantity int8
alter table public.order_items add column created_at timestamptz not null default now();
alter table public.order_items alter column quantity type bigint;

-- products: category_id -> categories.id; price float4; stock int2
alter table public.products add column category_id bigint references public.categories (id);
update public.products p set category_id = c.id from public.categories c where c.name = p.category;
alter table public.products alter column category_id set not null;
alter table public.products drop column category;
create index if not exists products_category_id_idx on public.products (category_id);
alter table public.products alter column price type real;
alter table public.products alter column stock type smallint;
